def glyph(ch):
    """The rows for `ch`, or `?` for anything not drawn."""
    if ch == " ":
        return []
    return GLYPHS.get(ch, GLYPHS["?"])


def width(ch):
    if ch == " ":
        return SPACE
    rows = glyph(ch)
    return max(len(r) for r in rows)
