#!/usr/bin/env python3
"""Writes src/font.ks: the overlay's 3x5 pixel font as Kestrel bitmasks.

Edit the glyph table here and rerun from examples/aerie:
    python3 tools/make_font.py
"""

GLYPHS = {
    'A': "010 101 111 101 101", 'B': "110 101 110 101 110", 'C': "011 100 100 100 011",
    'D': "110 101 101 101 110", 'E': "111 100 110 100 111", 'F': "111 100 110 100 100",
    'G': "011 100 101 101 011", 'H': "101 101 111 101 101", 'I': "111 010 010 010 111",
    'J': "001 001 001 101 010", 'K': "101 101 110 101 101", 'L': "100 100 100 100 111",
    'M': "101 111 111 101 101", 'N': "110 101 101 101 101", 'O': "010 101 101 101 010",
    'P': "110 101 110 100 100", 'Q': "010 101 101 110 011", 'R': "110 101 110 101 101",
    'S': "011 100 010 001 110", 'T': "111 010 010 010 010", 'U': "101 101 101 101 011",
    'V': "101 101 101 010 010", 'W': "101 101 111 111 101", 'X': "101 101 010 101 101",
    'Y': "101 101 010 010 010", 'Z': "111 001 010 100 111",
    '0': "111 101 101 101 111", '1': "010 110 010 010 111", '2': "110 001 010 100 111",
    '3': "110 001 010 001 110", '4': "101 101 111 001 001", '5': "111 100 110 001 110",
    '6': "011 100 111 101 111", '7': "111 001 010 010 010", '8': "111 101 111 101 111",
    '9': "111 101 111 001 110",
    '.': "000 000 000 000 010", ',': "000 000 000 010 100", ':': "000 010 000 010 000",
    '-': "000 000 111 000 000", '!': "010 010 010 000 010", '?': "110 001 010 000 010",
    '/': "001 001 010 100 100", "'": "010 010 000 000 000", '(': "010 100 100 100 010",
    ')': "010 001 001 001 010",
}

TEMPLATE = '''module Aerie

import linalg.(Vec4)

// A 3x5 pixel font for the overlay, so the HUD and title screen can show
// text without a font file. Each glyph is 15 bits, five rows of three from
// the top left; lowercase letters map to uppercase.
//
// Generated by tools/make_font.py; edit the table there, not here.

/// Glyph columns and rows.
let glyphWidth: Int64 = 3;
let glyphHeight: Int64 = 5;

/// The glyph bits for an ASCII byte; unknown bytes and spaces are blank.
func glyph(byte: UInt8) -> Int64 {
    match Int64(from: byte) {
        ARMS,
        _ => 0
    }
}

/// Width in pixels of `text` drawn at `scale` (one pixel per font dot).
func textWidth(text: String, scale: Float32) -> Float32 {
    var count: Int64 = 0;
    for _ in text.bytes { count = count + 1; }
    if count == 0 { 0.0 } else { Float32(from: count * (glyphWidth + 1) - 1) * scale }
}

/// Whether dot (row, col) of `bits` is lit.
func glyphDot(bits: Int64, row: Int64, col: Int64) -> Bool {
    (bits >> ((glyphHeight - 1 - row) * glyphWidth + (glyphWidth - 1 - col))) & 1 == 1
}

/// `text` as overlay rectangles with its top left at (x, y), shading from
/// `color` on the top row to `bottom` on the last. Each run of lit dots in
/// a glyph row becomes one rectangle, to keep the count low.
func textQuads(text: String, x x: Float32, y y: Float32, scale scale: Float32, color color: Vec4, bottom bottom: Vec4) -> [OverlayQuad] {
    let none = Vec4(x: -1.0, y: 0.0, z: 0.0, w: 0.0);
    var quads: [OverlayQuad] = [];
    var left = x;
    for byte in text.bytes {
        let bits = glyph(byte);
        var row: Int64 = 0;
        while row < glyphHeight {
            let rowColor = color + (bottom - color) * (Float32(from: row) / Float32(from: glyphHeight - 1));
            var col: Int64 = 0;
            while col < glyphWidth {
                var run: Int64 = 0;
                while col + run < glyphWidth and glyphDot(bits, row, col + run) {
                    run = run + 1;
                }
                if run > 0 {
                    quads.append(OverlayQuad(
                        rect: Vec4(x: left + Float32(from: col) * scale, y: y + Float32(from: row) * scale, z: Float32(from: run) * scale, w: scale),
                        color: rowColor, tile: none
                    ));
                }
                col = col + run + 1;
            }
            row = row + 1;
        }
        left = left + Float32(from: glyphWidth + 1) * scale;
    }
    quads
}

/// `text` shading from `color` to `bottom`, over a soft indigo shadow so it
/// reads over bright sky.
func gradientLabelQuads(text: String, x x: Float32, y y: Float32, scale scale: Float32, color color: Vec4, bottom bottom: Vec4) -> [OverlayQuad] {
    let offset = (scale * 0.5).ceil();
    let shadow = Vec4(x: 0.14, y: 0.14, z: 0.28, w: color.w * 0.75);
    var quads = textQuads(text, x: x + offset, y: y + offset, scale: scale, color: shadow, bottom: shadow);
    let lit = textQuads(text, x: x, y: y, scale: scale, color: color, bottom: bottom);
    quads.append(contentsOf: lit);
    quads
}

/// `text` in one color, over a soft shadow.
func labelQuads(text: String, x x: Float32, y y: Float32, scale scale: Float32, color color: Vec4) -> [OverlayQuad] {
    gradientLabelQuads(text, x: x, y: y, scale: scale, color: color, bottom: color)
}
'''

def main():
    arms = []
    for ch, rows in GLYPHS.items():
        bits = int(rows.replace(" ", ""), 2)
        codes = [ord(ch)] + ([ord(ch.lower())] if ch.isalpha() else [])
        arms.append(f"{' or '.join(map(str, codes))} => {bits}")
    with open("src/font.ks", "w") as f:
        f.write(TEMPLATE.replace("ARMS", ",\n        ".join(arms)))
    print(f"wrote src/font.ks ({len(GLYPHS)} glyphs)")

if __name__ == "__main__":
    main()
