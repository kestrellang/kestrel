#!/usr/bin/env python3
"""Regenerates tests/fixtures.ks: data compressed by Python's zlib and gzip
modules, which wrap the reference zlib. The inputs are rebuilt on the
Kestrel side by the same generator functions, so only compressed bytes are
stored."""
import gzip, zlib, os

def pattern(n): return bytes(i % 251 for i in range(n))
def text(n):
    words = b"the quick brown fox jumps over lazy dogs while kestrels hover above ".split()
    out, i = bytearray(), 0
    while len(out) < n:
        out += words[(i * 7 + i // 3) % len(words)] + b" "
        i += 1
    return bytes(out[:n])
def noise(n):
    state, out = 12345, bytearray()
    for _ in range(n):
        state = (state * 1103515245 + 12345) & 0x7FFFFFFF
        out.append((state >> 16) & 0xFF)
    return bytes(out)
def zeros(n): return bytes(n)

inputs = {
    "empty": b"",
    "hello": b"hello, hello, hello!",
    "pattern": pattern(3000),
    "text": text(8000),
    "noise": noise(1500),
    "zeros": zeros(100000),
}

def raw(data, level):
    c = zlib.compressobj(level, zlib.DEFLATED, -15)
    return c.compress(data) + c.flush()

cases = []
for name, data in inputs.items():
    for level in (1, 6, 9):
        cases.append((f"raw {name} level {level}", "raw", name, raw(data, level)))
    cases.append((f"zlib {name}", "zlib", name, zlib.compress(data, 6)))
    cases.append((f"gzip {name}", "gzip", name, gzip.compress(data, mtime=0)))

# Stored blocks.
cases.append(("raw pattern level 0", "raw", "pattern", raw(inputs["pattern"], 0)))
cases.append(("zlib hello level 0", "zlib", "hello", zlib.compress(inputs["hello"], 0)))

# A gzip member with a file name and comment, and two concatenated members.
named = bytearray(gzip.compress(inputs["hello"], mtime=0))
named[3] = 8 | 16
named[10:10] = b"hello.txt\x00a comment\x00"
cases.append(("gzip with name and comment", "gzip", "hello", bytes(named)))
cases.append(("gzip two members", "gzip", "hellohello",
              gzip.compress(inputs["hello"], mtime=0) + gzip.compress(inputs["hello"], mtime=0)))

out = ["// Generated by make_fixtures.py from Python's zlib and gzip modules. Do not edit.",
       "", "module deflate_tests_fixtures", "",
       "struct Fixture {", "    let name: String;", "    let format: String;",
       "    let input: String;", "    let compressedHex: String;", "}", "",
       "func fixtures() -> Array[Fixture] {", "    ["]
for i, (label, fmt, name, blob) in enumerate(cases):
    comma = "," if i < len(cases) - 1 else ""
    out.append(f'        Fixture(name: "{label}", format: "{fmt}", input: "{name}", compressedHex: "{blob.hex()}"){comma}')
out += ["    ]", "}", ""]
open(os.path.join(os.path.dirname(__file__), "fixtures.ks"), "w").write("\n".join(out))
print(f"{len(cases)} fixtures")
