#!/usr/bin/env python3
"""Writes pngsuite_expected.ks: what each PngSuite file should decode to.

Each valid file's pixels are reduced to 8-bit RGBA (16-bit samples keep
their high byte, as Pillow does) and summarized by size and CRC-32. Files
whose names start with "x" are corrupt and must fail to decode.

Usage: python3 lang/images/tests/make_fixtures.py   (needs Pillow and numpy)
"""
import os
import zlib

import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
SUITE = os.path.join(HERE, "pngsuite")


def rgba8(path):
    image = Image.open(path)
    image.load()
    mode = image.mode
    if mode in ("I;16", "I;16B", "I"):
        # Pillow keeps 16-bit gray as integers; take the high byte.
        values = (np.array(image).astype(np.uint32) >> 8).astype(np.uint8)
        alpha = np.full(values.shape, 255, np.uint8)
        trns = image.info.get("transparency")
        if trns is not None:
            alpha[np.array(image) == trns] = 0
        return np.dstack([values, values, values, alpha]).tobytes()
    trns = image.info.get("transparency")
    with open(path, "rb") as f:
        depth = f.read(25)[24]
    if mode == "L" and trns is not None and depth < 8:
        # Pillow compares tRNS's raw sample against the scaled-up value;
        # the spec compares raw samples, so scale it first.
        values = np.array(image)
        alpha = np.where(values == trns * 255 // ((1 << depth) - 1), 0, 255).astype(np.uint8)
        return np.dstack([values, values, values, alpha]).tobytes()
    return image.convert("RGBA").tobytes()


def main():
    lines = [
        "// Generated by make_fixtures.py from the PngSuite images; do not edit.",
        "",
        "module images_tests",
        "",
        "struct Expected {",
        "    let name: String;",
        "    let width: Int64;",
        "    let height: Int64;",
        "    /// CRC-32 of the pixels as 8-bit RGBA; ignored when `valid` is false.",
        "    let crc: Int64;",
        "    let valid: Bool;",
        "}",
        "",
        "func pngSuite() -> Array[Expected] {",
        "    [",
    ]
    entries = []
    for name in sorted(os.listdir(SUITE)):
        if not name.endswith(".png"):
            continue
        path = os.path.join(SUITE, name)
        if name.startswith("x"):
            entries.append(f'        Expected(name: "{name}", width: 0, height: 0, crc: 0, valid: false)')
            continue
        width, height = Image.open(path).size
        crc = zlib.crc32(rgba8(path))
        entries.append(f'        Expected(name: "{name}", width: {width}, height: {height}, crc: {crc}, valid: true)')
    lines.append(",\n".join(entries))
    lines += ["    ]", "}", ""]
    with open(os.path.join(HERE, "pngsuite_expected.ks"), "w") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    main()
